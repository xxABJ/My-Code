# Variable = a container for a value. Behaves as the value that it contains.
# Just like x in maths! They can be words numbers or even boolean.
# Example: (x = "Bro") or (y = 21) or (z = False)
# String = a series of characters. Can not be used is any sort of maths.
# You can add a string concatenation to combine it with other types of variables.
# String concatenation = adding +str to print without errors

name = "Abj"
print(name)

# Able to add a string before a variable.
print("Hello "+name)

# Able to check the data type of a variable.
print(type(name))

# Other combination of variables (name-wise)
first_name = "Ali"
last_name = "Jassim"
# Adding space is always nice !
full_name = first_name + " " + last_name

print("Hello "+full_name+" !")