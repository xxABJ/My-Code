# float = a floating point number, a decimal number!
# The float data type is a numerical value that can store a number that includes a decimal portion.
# An int data type can not store a decimal portion, it can only store whole numbers.

height = 169.8
print(height)
print(type(height))

# Now we add it to a sting !
print("Your height is: " + str(height) + "cm")