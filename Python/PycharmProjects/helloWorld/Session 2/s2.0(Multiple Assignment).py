# Multiple assignment = allows the ability to assign multiple variables in one line of code.

# Instead of writing in multiple lines:

# name = "Ali"
# age = 25
# adult = True
# height = 169.8
# weight = 80

# print(name)
# print(age)
# print(adult)
# print(height)
# print(weight)

# You can write it in one line using multiple assignment, but has to be separated by a comma ",".
# Also allocate the data types in the orderly fashion:

name, age, adult, height, weight = "Ali", 25, True, 169.8, 80

print(name)
print(age)
print(adult)
print(height)
print(weight)
